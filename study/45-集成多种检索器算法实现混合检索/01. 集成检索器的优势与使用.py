# 一直压到 0.02 才翻转。而 0.02 基本等于"把 BM25 关掉"。
#
# 为什么会这样?算一下就懂了。设 BM25 权重 w,向量权重 1-w:
#     清洁保养 只在向量出现且排第 1     -> 得分 (1-w)/61
#     固件2.0.8 两路都有(BM25第1、向量第3) -> 得分 w/61 + (1-w)/63
# 要让正确答案赢:
#     (1-w)/61 > w/61 + (1-w)/63
# 化简得  w < 2/65 ≈ 0.031
#
# ★ 也就是说,**BM25 的权重要压到 3% 以下**才有效果 —— 而权重加起来是 1,
