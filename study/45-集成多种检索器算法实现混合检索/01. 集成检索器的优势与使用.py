# ============================================================================
# 第 0 部分:为什么要"集成"——单一算法的盲区
# ============================================================================
#
# 前面几章用的检索器,不管怎么调参数,本质上都是**一种算法**。
# 而每一种算法都有自己的"瞎区",并且这些瞎区**不重叠**:
#
#   向量检索(语义)  强在"意思相近但用词不同",弱在"精确的编号/型号/代号"
#                    —— 因为 embedding 模型没见过 K87、SP-4417 这种词,
#                       它把这类符号编码得模模糊糊,几个不同型号之间分不开。
#
#   BM25(关键词)   强在"精确匹配",弱在"同义词"
#                    —— 它纯粹数字符串重合度,"键盘"和"键帽"在它眼里毫无关系。
#
# 关键在于:**一方的弱点恰好是另一方的强项**。那让两个都跑一遍,再把结果合起来,
# 岂不是两边的好处都占了?这就是"集成检索器(Ensemble Retriever)"。
#
# ===== 但先泼一盆冷水 =====
# "合并"这两个字里藏着全部难点。你有两串排名完全不同的结果:
#
#     向量给:  [A, B, C]      BM25 给: [C, D, A]
#
# 怎么合成一个?不能简单按分数加 —— 因为**两边的分数根本不可比**:
# 向量的分数是余弦相似度(0~1),BM25 的分数是个没有上界的原始分(可能是 12.7)。
# 拿 0.83 和 12.7 相加,纯属胡来。
#
# 本文件要讲的就是:**怎么合**、**合完到底好不好**。
# 第二个问题的答案会让你意外 —— 请务必看完第 4 部分。


