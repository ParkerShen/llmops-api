# ============================================================================
# 第 7 部分:参数速查 & 什么时候该用
# ============================================================================
#
#   EnsembleRetriever(
#       retrievers = [...],        # 要集成的检索器列表,至少 2 个
#       weights    = [...],        # 权重,长度必须 == retrievers 长度
#                                  # 不传则均分 [1/n, 1/n, ...]
#                                  # 长度不匹配会 ValueError
#                                  # 至少有一个要 > 0
#       c          = 60,           # RRF 常数,必须是**整数**
#                                  # 越小越看重高排名,越大越看重多路共识
#       id_key     = None,         # 去重依据。默认用 page_content;
#                                  # 若同一文档在不同检索器里内容有细微差别,
#                                  # 可以指定 metadata 里的字段当唯一键
#   )
#
#   其他要点:
#     - 去重默认按**文档全文**。所以只要你两路返回的是同一批 Document 对象,
#       去重就有效;但如果你两路分别从不同数据源构造文档,
#       page_content 有一点不同就会被当成两条。
#     - 同步调用时,各路检索器是 **for 循环串行**跑的;
#       用 .ainvoke() 才会 asyncio.gather 并发。
#     - 它返回的是**排序过的**结果(和上一章的 MultiQueryRetriever 不同)。
#
#   ===== 什么时候该用 =====
#     你的两路检索器**都靠谱**,只是强项不同        -> 用,这是它发挥的前提
#     查询里大量出现精确编号/型号/代码(商品库、日志、工单)
#                                                   -> 用,BM25 那一路价值最大
#     其中一路在某些查询上会完全失效                  -> **慎用**,先修那一路
#     你没法给两路合理分配权重                        -> 别用等权硬上
#     延迟敏感,而其中一路要访问远端服务              -> 注意串行调用的耗时
#
#   ===== 最该记住的一句 =====
#     集成**没有**提升单路的准确率,它提升的是"召回覆盖面"。
#     代价是把两路的错误也一起放大了。用之前先确认:
#     **两路是不是都足够靠谱?** 如果有一路是拖后腿的,集成只会让它拖得更狠。
#
#   顺带一提:工业界更常见的组合不是"向量 + BM25",而是
#   "向量粗召回(召回 50~100 条)+ Rerank 精排(取前 5 条)"。
#   后者能真正提升精度,因为它有一个**会判断相关性**的模型在做最后裁决,
#   而不是像 RRF 这样只数名次。


# ============================================================================
# 小结
# ============================================================================
#   机制一句话:多路检索 → 各自排名 → 用 RRF 公式 Σ 权重/(排名+c) 合并 → 排序输出。
#   精髓在于**只用排名、不用分数**,从而绕开"不同算法的分数不可比"这个难题。
#
#   三个必记的点:
#     1. 中文用 BM25Retriever **必须传 preprocess_func**(如 jieba),
#        否则默认的 text.split() 会把中文切得面目全非
#     2. RRF 奖励"多路共识"而不是"单路高分",c=60 让这个倾向非常强
#        结果就是:**单路的第 1 名,可能干不过两路的第 3 名**
#     3. 权重不是万能调节钮 —— 实测要压到 3% 以下才有效,那等于关掉一路
#
#   本文件实测的诚实结论:
#     四个查询里,集成 2 胜 2 负。它**不是**无条件的改进项。
#     用它之前先确认每一路都靠谱;有一路在拖后腿的话,集成会放大它的错误。
