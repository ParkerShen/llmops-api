# ============================================================================
# 第 0 部分:为什么要按问题类型换 Prompt 模板
# ============================================================================
# 前面几章的套路是"一个模板 + 一堆检索结果 -> 生成答案"。
# 但用户的问题不是一种。看这三个:
#
#   "怎么给 Python 项目建虚拟环境"   -> 他要**照着做**,要的是命令和步骤
#   "为什么 Python 有多线程还要 GIL" -> 他要**想明白**,要的是原理和类比
#   "Python 和 Go 学哪个好"          -> 他要**做决定**,要的是推荐和权衡
#
# 拿同一个模板回答这三种,必然有一种不对味:
#   如果模板写"你是动手向导,只给步骤" -> 问"为什么"的人拿不到解释
#   如果模板写"你是讲原理的老师"      -> 问"怎么装"的人拿到一堆理论,还是不会装
#   如果模板写"请全面详细地回答"      -> 三种问题的答案都一样长、一样平,没有侧重
#
# 所以 Prompt 模板本身也是一份"该往哪个方向回答"的配置,
# 而选哪一份,正好是上一节语义路由在干的事 —— 换的只是"选中之后拿去干嘛":
#
#   46 第 4 部分:  语义路由 -> 选**检索器** -> 去哪个库查
#   本节:          语义路由 -> 选**Prompt 模板** -> 用哪种人设答
#
# ⚠️ 关于"官方那个 SemanticRouter"
#   视频里用的是 LangChain 的 SemanticRouter 类,它依赖一个叫 semantic-router 的第三方包
#   (还要自己配 encoder,默认走 OpenAI)。你环境里**没装这个包**,而且 LangChain 1.x
#   也没把它放进 langchain_classic,import 会直接失败。
#   所以下面我们**手写**这套逻辑 —— 其实总共就三步:转向量、算余弦、取最高分。
#   手写一遍你会看清它没有任何魔法,之后要不要装那个包,只是"要不要用别人的封装"的问题。

import dotenv
import numpy as np  # 算余弦相似度用

from langchain_core.output_parsers import StrOutputParser
from langchain_core.prompts import ChatPromptTemplate
from langchain_deepseek import ChatDeepSeek
from langchain_huggingface import HuggingFaceEmbeddings

dotenv.load_dotenv()

# 本地 embedding 模型,已缓存,不联网、不花钱 —— 这正是语义路由的最大优势
embedding = HuggingFaceEmbeddings(model_name="BAAI/bge-small-zh-v1.5")

llm = ChatDeepSeek(model="deepseek-chat", temperature=0)


# ============================================================================
# 第 1 部分:三份 Prompt 模板(人设)
# ============================================================================
# 每份模板都在做同一件事:**把模型的"回答姿态"钉死**。
# 注意它们不是"礼貌用语"上的区别,而是**输出结构**上的区别:
#   howto   -> 编号步骤 + 可执行命令
#   concept -> 一句话结论 + 类比 + 边界条件
#   compare -> 明确推荐 + 权衡 + 反例场景
#
# 写模板时有个实用技巧:**明确说"不要做什么"**。
# 比如 howto 里写"不要讲原理"、concept 里写"不要给操作步骤" ——
# 模型天生爱"全面",不明确禁止,它就会把三种都写一遍,等于没路由。

SYSTEM_PROMPTS = {
    "howto": (
        "你是一个动手向导。用户想把某件事做出来。"
        "回答用 1. 2. 3. 编号,每一步给出可直接执行的命令或代码。"
        "不要讲原理,不要寒暄,不要建议用户去看文档。"
    ),
    "concept": (
        "你是一个讲原理的老师。用户想知道某件事为什么会这样。"
        "回答先给一句话结论,再用一个生活化的类比解释机制,"
        "最后说清楚这个机制在什么情况下会失效。"
        "不要给操作步骤,用户此刻不需要动手。"
    ),
    "compare": (
        "你是一个技术选型顾问。用户在几个选项之间犹豫。"
        "回答先直接给出推荐(不要和稀泥说'看情况'),"
        "再列 2 条最关键的权衡,最后说清楚什么情况下该选另一个。"
        "不要说'两者各有优劣'这种废话。"
    ),
}


# ============================================================================
# 第 2 部分:语义路由 —— 这次用"示例问句"而不是"抽象描述"
# ============================================================================
# 这是本节相对 46 第 4 部分的**关键改进**,值得慢慢看。
#
# 46 里我们给每个意图写的是**一句抽象描述**:
#     "python": "Python 编程语言相关的问题,包括语法、标准库、包管理、并发模型"
# 抽象描述有个毛病:**它是"归纳"出来的话,而用户提问用的是"具体"的话。**
# 用户不会说"我想问一个包管理相关的问题",他会说"pip 装不上包怎么办"。
# 你拿一句归纳去比一句具体,语言风格差得远,相似度自然不高、也不稳。
#
# 更靠谱的做法:**每个意图配几条用户真实会说的话**,匹配时只要跟**任意一条**像就行。
# 这就是官方 SemanticRouter 里 "utterances"(话语示例)的设计思路。
#
# 所以下面每个意图配了 4 句示例。这几句不是随便编的,它们要覆盖:
#   不同的问法(怎么/如何/求助)、不同的用词(装/配置/报错),
#   以及同一个意图里不同的子话题。

ROUTE_UTTERANCES = {
    "howto": [
        "怎么安装 Python",
        "如何给项目创建虚拟环境",
        "pip 装不上包怎么办",
        "这个功能具体怎么实现",
    ],
    "concept": [
        "为什么 Python 有多线程还要 GIL",
        "装饰器的原理是什么",
        "这个机制背后是怎么工作的",
        "为什么要这样设计",
    ],
    "compare": [
        "Python 和 Go 学哪个好",
        "这两个方案哪个更合适",
        "该选哪个框架",
        "哪个性能更好一些",
    ],
}

# ---- 预计算:把所有示例问句一次性转成向量 ----
# ★ 注意这个循环是写在**函数外面**的。这些向量跟用户问什么无关,
#   启动时算一次就够了。放进函数里的话,每问一次就要重算 12 条,纯浪费。
#   真实项目里这些向量还会存进数据库/缓存,服务启动时加载。
route_examples = []  # [(意图名, 向量), ...] —— 故意拍平成一维列表,方便下面取 max
for _name, _examples in ROUTE_UTTERANCES.items():
    for _vec in embedding.embed_documents(_examples):  # 一批进,一批出
        route_examples.append((_name, _vec))


def cosine(a, b):
    """余弦相似度:两个向量夹角的余弦,范围 -1 ~ 1,越接近 1 方向越一致。"""
    return float(np.dot(a, b) / (np.linalg.norm(a) * np.linalg.norm(b)))


def semantic_route(query: str):
    """返回 (选中的意图, 该意图的最高分, {每个意图的最高分})。"""

    q_vec = embedding.embed_query(query)  # 一个字符串进,一个向量出

    best_name, best_score = None, -1.0
    per_route = {}  # 每个意图自己的最高分,只为打印好看

    for name, vec in route_examples:
        score = cosine(q_vec, vec)

        # ★ 这里是"示例问句"方案的核心:跟**每一条**示例都比,
        #   全局最高分决定选谁 —— 相当于"只要跟任意一条像就算像"。
        if score > best_score:
            best_name, best_score = name, score

        # 同一个意图的多条示例里,只留最高的那条(哪条最像不重要,意图才重要)
        if score > per_route.get(name, -1.0):
            per_route[name] = score

    return best_name, best_score, per_route


# ============================================================================
# 第 3 部分:用选中的模板回答
# ============================================================================

# 把"模板名字 -> 完整链条"预先建好,和向量是一个道理:配置是静态的,别每次重搭。
# 链条结构就是第 3 章学的老三样:Prompt -> 模型 -> 解析成字符串
CHAINS = {
    name: ChatPromptTemplate.from_messages([("system", sys_prompt), ("human", "{q}")])
    | llm
    | StrOutputParser()
    for name, sys_prompt in SYSTEM_PROMPTS.items()
}

QUESTIONS = [
    "怎么给 Python 项目建虚拟环境",     # 期望 howto
    "为什么 Python 有多线程还要 GIL",   # 期望 concept
    "Python 和 Go 学哪个更有前途",      # 期望 compare
]

print("=" * 78)
print("第 3 部分:语义路由选模板,再看回答")
print("=" * 78)

for q in QUESTIONS:
    name, score, per_route = semantic_route(q)
    scores_str = "  ".join(f"{k}={v:.3f}" for k, v in per_route.items())

    print(f"\n{'=' * 78}")
    print(f"查询: {q}")
    print(f"  各意图最高分: {scores_str}")
    print(f"  -> 选中模板: {name}  (得分 {score:.4f})")
    print(f"{'-' * 78}")

    answer = CHAINS[name].invoke({"q": q})
    # 只印前 150 字,不然终端太长;完整答案你自己跑的时候可以去掉切片
    print(answer[:150].replace("\n", " ") + " ...")


# ============================================================================
# 第 4 部分:对照实验 —— 不路由会怎样
# ============================================================================
# 上面光看"路由选对了"还不够,得看到**选错了/不选**的代价。
# 拿同一个问题,分别用三个模板各答一遍,对比姿态差别。

COMPARE_Q = "为什么 Python 有多线程还要 GIL"

print()
print("=" * 78)
print("第 4 部分:同一个问题,三份模板分别回答")
print("=" * 78)
print(f"\n问题: {COMPARE_Q}\n")

for name in SYSTEM_PROMPTS:
    answer = CHAINS[name].invoke({"q": COMPARE_Q})
    print(f"{'-' * 78}")
    print(f"【{name} 模板】")
    print(answer[:150].replace("\n", " ") + " ...")

# 跑完你会看到三种完全不同的姿态:
#   howto   会给你"步骤 1. 2. 3."—— 但问的是"为什么",步骤答非所问
#   concept 会先给结论再打比方 —— 这才是这个问题该有的回答
#   compare 会硬给你一个"推荐",还会说"什么情况下该选另一个"—— 莫名其妙
#
# ★ 三份模板本身都没有错,**错的是配错了问题**。
#   这就是 Prompt 模板也需要路由的原因:模板是"回答姿态",而姿态必须匹配提问意图。


# ============================================================================
# 第 5 部分:★ 诚实的评估 —— 以及怎么看出"它在瞎猜"
# ============================================================================
# 上面的实测有个坑:**测试题就是我写的示例句本身**。
# 你看第 3 部分那一行 "concept=1.000" —— 满分。为什么?因为问的那句话
# 跟我写进 ROUTE_UTTERANCES 的示例**一字不差**,它跟自己比当然完全一样。
#
# 这是评估路由器的头号陷阱:**拿示例去测自己,永远 100%。**
# 必须换一批"没见过的问法"再测,才知道真实水平(2026-09-16 实跑):
#
#   提问                             howto  concept  compare   选中     对?
#   ---------------------------------------------------------------------
#   怎么装 Python 环境变量要配吗       0.718    0.557    0.496   howto    OK
#   GIL 到底锁的是什么                 0.409    0.490    0.390   concept  OK
#   学 Python 好还是学 Go 好找工作     0.631    0.555    0.909   compare  OK
#   我想把项目依赖隔离起来该怎么做      0.518    0.454    0.491   howto    OK
#   这两个库我该用哪个                 0.495    0.380    0.598   compare  OK
#   为什么异步 IO 能提升吞吐           0.425    0.402    0.438   compare  MISS ★
#
# 6 条对了 5 条。但比"5/6"更重要的是**看分数**:
#
#   判对的那些,第一名都明显领先:
#       0.909 vs 0.631(差 0.28)  0.718 vs 0.557(差 0.16)
#   判错的那一条,三个分数挤在一起:
#       0.438 / 0.425 / 0.402   —— 最大差距只有 0.04
#
# ★★ 结论:**它判错的时候,是"没把握"地判错的,而分数把这份没把握暴露了出来。**
#
#   于是有个非常实用的抓手 —— 别只看"谁最高",要看**最高比第二高多少**:
#
#       gap = 第一名得分 - 第二名得分
#
#       gap 大(比如 > 0.05) -> 这次的判断有依据,可以用
#       gap 小(比如 < 0.05) -> 基本等于抛硬币,**放弃路由,走兜底**
#
#   这就是所有生产级语义路由都会配的"兜底分支",和 46 章那个 other 是同一个思路:
#   模型/算法一定有说不准的时候,好的系统会**知道自己什么时候说不准**。
#
# ===== 它为什么会错? =====
#   "为什么异步 IO 能提升吞吐" 问的是**性能**,而我们给 concept 配的 4 句示例
#   全在讲 **Python 内部机制**(GIL、装饰器、设计动机)—— 一个性能相关的词都没有。
#   compare 那边倒是有 "哪个性能更好一些",于是被它抢走了。
#
#   ★ 教训:**示例没覆盖到的话题,路由器就是瞎的。**
#     示例句不是"随便写几句就行",它得覆盖这个意图下**用户可能问的各种子话题**。
#     一个判断标准:每句示例问自己"这句话里的关键词,在别的意图里有对应吗?"——
#     如果某个子话题一句示例都没有,那这类问题必然飘。
#
# ===== 收尾:两条设计规矩 =====
#   1. **示例句必须来自真实提问**,不能自己编。编出来的句子是"标准话术",
#      而真人提问是"半句话 + 错别字 + 口语",两者向量差得远。
#      有真实日志就抽 20 条,没有就先让业务方想"用户都怎么问"。
#   2. **评估必须用没见过的问法**,并且**看 gap 不只看对错**。
#      只看准确率你会以为"5/6 挺好",看 gap 才发现其中有一条是运气。
#
# ===== 最后:语义路由到底该不该用 =====
#   优势:  快(一次 embedding,本地几毫秒)、免费、能离线、意图加到 100 个也不加钱
#   劣势:  只认"字面/语义上像",不认识"因果关系";示例没覆盖就失效;
#          意图多了之后,相邻意图会互相干扰(分数全挤在一起)
#
#   一个常用的判断标准:
#     意图**边界清晰、问法固定** -> 语义路由(比如"技术问题 vs 闲聊")
#     意图**需要推理才能分辨**   -> 逻辑路由(让模型读,比如 46 章那种)
#   两者也可以串起来:语义路由做第一层粗筛,拿不准的丢给大模型判断。
