#      停止条件在模型手里 → 你就得加 ToolCallLimitMiddleware。
#      错误处理交给中间件 → 你就得想清楚哪些异常该翻译。
#
#      这是 Agent 开发的真实成本：
#      不是写代码难，是【你要替一个不确定的东西想清楚边界】。
