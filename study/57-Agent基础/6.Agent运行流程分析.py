# ============================================================
# 【概念 1】：Agent 是一张图，图可以打印出来
#
# 文件 3 我说过：create_agent 返回的是 CompiledStateGraph —— 一张图。
# 图不是比喻，它是真的对象，可以画出来：
#
#     print(agent.get_graph().draw_mermaid())
#
# 我在你环境里跑过了，输出长这样（我剔掉了样式部分）：
#
#     graph TD;
#         __start__([__start__]) :::first
#         model(model)
#         tools(tools)
#         __end__([__end__]) :::last
#         __start__ --> model;
#         model -.-> __end__;
#         model -.-> tools;
#         tools -.-> model;
#
# 四个节点，四条边：
#
#        __start__
#            │  实线
#            ▼
#        ┌────────┐   虚线   ┌─────────┐
#        │ model  │ ───────▶ │ __end__ │
#        └────────┘          └─────────┘
#            │  虚线
#            ▼
#        ┌────────┐
#        │ tools  │
#        └────────┘
#            │  虚线
#            └──────────▶ 回到 model
#
# ⚠️ 注意那个 return 到 model 的虚线 —— 那就是你 55 章手写的 while 的"回头路"。
#
# ------------------------------------------------------------
# 【实线和虚线的区别，就是 Chain 和 Agent 的分界线】
#
#   实线 = 无条件边：走完 A 一定走 B，写死在图里。
#   虚线 = 条件边（conditional edge）：走 A 之后去哪，要看【运行时的状态】。
#
#   我在你环境里查了这四条边的属性，结果是：
#
#       __start__ -> model      conditional=False     ← 唯一的实线
#       model     -> __end__    conditional=True
#       model     -> tools      conditional=True
#       tools     -> model      conditional=True
#
#   也就是说：【出了起点以后，这张图里每一条边都是条件的。】
#
#   对比文件 1 那个 Chain：它的边全是实线。
#   pipeline 一旦 invoke，从第一步到最后一步，一步不落、一步不错。
#
#   Agent 的图里没有"一定"，只有"看情况"。这就是本质区别。
#
# ============================================================


# ============================================================
# 【概念 2】：停止条件是什么 —— 模型说"我不调工具了"
#
# 那两张虚线票（model → tools / model → __end__）由谁决定？
#
# 由图上的【路由函数】决定（LangGraph 叫 conditional edge 的判断函数）。
# 而在 Agent 这张图里，它判断的东西非常朴素：
#
#     看 model 节点刚输出的那条 AIMessage —— 它的 tool_calls 是空的吗？
#
#       tool_calls 有内容  →  走 model -> tools   （还有活要干，回去干活）
#       tool_calls 是 []   →  走 model -> __end__ （我没活干了，收工）
#
# ⚠️ 所以答案是：**喊停的是模型自己。**
#
#   不是框架数圈数，不是你写了个 max_rounds，不是任何外部的判断。
#   是模型在某一轮里输出了一条【没有 tool_calls 的 AIMessage】——
#   那个空列表，就是停止信号。
#
#   回头看文件 3 那个现象：问"你好"只有 2 条消息，问天气有 4 条。
#   差别就是：第一轮模型就输出了空 tool_calls，图直接走 __end__ 出图了。
#
#   回头看文件 4：模型读完 ToolMessage 里那句 Error 之后，
#   决定"不再试了，直接回答" —— 那个决定，也是它输出的空 tool_calls。
#
# ------------------------------------------------------------
# 【这个设计很美，但它有一个可怕的副作用】
#
#   停止条件掌握在模型手里 —— 那模型要是【一直不肯停】呢？
#
#   比如你的工具描述写得太宽泛，模型每一轮都觉得"我还能再查一下"，
#   它就会一直 model -> tools -> model -> tools -> ...
#
#   LangGraph 有个兜底：recursion_limit（超了会抛 GraphRecursionError）。
#
#   但我在你环境里查了这个默认值（langgraph/_internal/_config.py）：
#
#       DEFAULT_RECURSION_LIMIT = int(getenv("LANGGRAPH_DEFAULT_RECURSION_LIMIT", "10007"))
#
#   ⚠️ 一万零七。不是 25，不是 100 —— 是 10007。
#
#   这个数字意味着：等你撞上 GraphRecursionError 的时候，
#   它已经跑了大约 5000 轮（每轮 model + tools 两步），
#   token 早就烧完了。**这个兜底是给程序用的，不是给你的钱包用的。**
#
#   所以真实项目里必须自己加护栏 —— 框架内置了中间件：
#
#       from langchain.agents.middleware import ToolCallLimitMiddleware
#
#       ToolCallLimitMiddleware(
#           run_limit=5,              # 单次 invoke 最多调 5 次工具
#           thread_limit=20,          # 整个会话最多 20 次
#           exit_behavior="continue", # 超了不报错，让模型基于现有信息收尾
#       )
#
#   ⚠️ 又是中间件。文件 4 你用中间件兜异常，这里用中间件限次数 ——
#      同一个插槽，插不同的东西。这就是 1.x 的设计方式。
#
# ============================================================


