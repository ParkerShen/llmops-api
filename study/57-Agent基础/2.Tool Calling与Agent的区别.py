# ============================================================
# 【今天要理解的概念】：Tool Calling 是"说"，Agent 是"做"
#
# 先回答上一个文件留的问题：
#
#   你 55 章手写的 while 圈，和 Agent 的环，形状一模一样。
#   为什么 55 章写得那么费劲，框架里几行就能建一个？
#
# 因为 55 章你【同时干了三件事】：
#
#   ① 让模型决定调哪个工具      ← 这是模型的能力
#   ② 真的去执行那个工具        ← 这是你的代码在干
#   ③ 把结果喂回去，再问一遍     ← 这还是你的代码在干
#
#   而 LangChain 里，① 叫 Tool Calling，②③ 叫 Agent。
#
# ------------------------------------------------------------
# 【准确地说：Tool Calling 不是"调用了工具"】
#
#   名字有误导性。模型从来没有"调用"过任何东西。
#   模型做的唯一一件事是：输出一段 JSON，说"我想调 get_weather，
#   参数是 {"city": "深圳"}"。
#
#   然后呢？—— 然后就没有然后了。
#
#   · 模型没有去查天气
#   · 模型不知道 get_weather 执行成功了还是报错了
#   · 模型不会自己决定"那我再调一次"
#
#   它只是喊了一声。喊完之后，谁去执行、要不要再问它一次、
#   什么时候停 —— 全是【你的代码】的事。
#
# ------------------------------------------------------------
# 【用你熟悉的前端思维类比】
#
#   Tool Calling ≈ 子组件 emit 了一个事件
#
#       emit('fetch-weather', { city: '深圳' })
#
#       组件喊完了，它自己也停在那儿了。它不知道父组件有没有监听，
#       不知道请求发了没有，不知道结果是什么 —— 它只负责"喊"。
#
#   Agent ≈ 那个父组件 + 整个更新循环
#
#       监听事件 → 真的发请求 → 拿到数据 → 把数据传回去 → 再看子组件
#       要不要继续喊 → 不要了，收工。
#
#   所以 bind_tools() 给你的，只是一个"会 emit 事件的子组件"。
#   它不会自己转起来。
#
# ------------------------------------------------------------
# 【一句话总结】
#
#   Tool Calling 是 Agent 的一个【零件】，不是 Agent。
#   Agent = Tool Calling + 执行器 + 循环 + 停止条件。
#
#   （55 章你把这四个都手写了，所以累。今天开始学的是：
#     后面三个，框架替你写。）
# ============================================================


