from typing import Annotated

import dotenv
from langchain_core.tools import tool
from langchain_deepseek import ChatDeepSeek
from pydantic import Field
dotenv.load_dotenv()

@tool
def get_weather(city: Annotated[str,Field(description="要查询天气的城市，例如：北京")])->str:
    """查询指定城市的天气"""
    return f"{city}今天天气晴朗，温度 25℃"

llm  = ChatDeepSeek(model="deepseek-chat",temperature=0)


llm_with_tools = llm.bind_tools([get_weather])
ai_msg = llm_with_tools.invoke("深圳今天天气怎么样？")

print("【1】content:", repr(ai_msg.content))
print("【2】tool_calls:", ai_msg.tool_calls)
print("【3】工具执行了吗：")
print(get_weather.invoke({"city": "北京"})) #  ← 你自己动手调，对比着看


