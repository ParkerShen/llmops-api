# ============================================================
# 本文件要搞明白的一件事：
#
#   上一章你写了 6 个文件，但每个文件里都只有 1 个工具。
#   真实的 Agent 不可能是这样 —— 一个客服 Agent 要会查天气、
#   查订单、算运费、查退货政策……所以工具一定是「一群」。
#
#   一旦工具变成一群，就出现了一个新问题：
#
#      LLM 怎么知道该用哪一个？
#
#   答案是：它只看得到每个工具的「名片」——
#   name、description、参数 schema。看不到你的函数体。
#
#   所以本文件的目标不是写多难的逻辑，而是：
#   亲手把这张「菜单」打印出来看一眼。
# ============================================================

# ============================================================
# 第 1 步：导入
#
# 回顾上一章：@tool 装饰器从哪来？消息类型从哪来？
# 这一章还是那几样东西，先写着，缺了再补。
#
# TODO(你写)：写 import 语句
# ------------------------------------------------------------
from typing import Annotated

from langchain_core.tools import tool
from pydantic import Field

# ============================================================
# 第 2 步：写第 1 个工具
#
# 要求：
#   1. 参数是字符串（比如城市名、订单号、商品名）
#   2. 函数体 return 一句假数据就行，不用真联网
#   3. docstring 用中文写清楚「什么时候该调它」
#
# 建议场景：查天气  →  get_weather(city: str)
#
# TODO(你写)：
# ------------------------------------------------------------
@tool
def get_weather_info(city:Annotated[str, Field(description="城市名称")]) -> str:
    """查询天气信息"""
    return f"{city}的天气是晴天"

# ============================================================
# 第 3 步：写第 2 个工具
#
# 场景：查订单状态 → get_order_status(order_id: str)
#
# 关键判断（这是本文件的重点，慢一点想）：
#
#   现在你有两个工具，它们的参数都是 str。
#   假如你把两个 docstring 都写成「查询信息」，会怎样？
#
#   → LLM 分不出来，只能瞎选一个。
#
#   所以每个 docstring 必须回答同一个问题：
#   「用户说了什么话的时候，你才该来找我？」
#
# TODO(你写)：
# ------------------------------------------------------------
@tool
def get_order_status(order_id: Annotated[str, Field(description="当前订单号")]) -> str:
    """根据订单ID查询订单状态"""
    return f"订单{order_id}的状态是已支付"
# ============================================================
# 第 4 步：把多个工具装进一个列表
#
# 上一章 bind_tools 里你只放了一个工具，还记得写法吗？
# bind_tools([...]) 里的中括号说明，它要的本来就是一个「列表」。
#
# 先定义一个变量，比如 TOOLS = [工具1, 工具2]
#
# TODO(你写)：
# ------------------------------------------------------------
tools = [get_weather_info, get_order_status]

# ============================================================
# 第 5 步：打印「菜单」（本文件最值钱的一步）
#
# 用循环遍历那个列表，把每个工具的这几样东西打出来：
#
#   name          → LLM 看到的工具名
#   description   → LLM 看到的说明（就是你的 docstring）
#   args          → LLM 看到的参数表
#
# 提示：上一章你用过 get_logistics_fee.args，
#       想一想 name 和 description 这两个属性叫什么名字。
#
# 打印完盯着输出看三秒，然后问自己：
#   「如果我是 LLM，只看这些字，我能分清这两个工具吗？」
#
# TODO(你写)：
# ------------------------------------------------------------
for tool in tools:
    print("=" * 60)
    print(f"name: {tool.name}")
    print(f"description: {tool.description}")
    print(f"args: {tool.args}")

# ============================================================
# 第 6 步：自测
#
# 每个工具都 invoke 一次，确认参数名没写错
# （invoke 里传的是字典，key 要和你函数定义的参数名一模一样）
#
# TODO(你写)：
# ------------------------------------------------------------
print(get_order_status.invoke({"order_id": "12345"}))
print(get_weather_info.invoke({"city": "北京"}))

