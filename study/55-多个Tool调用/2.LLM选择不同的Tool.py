#
# 为什么不能 import？
#   你上一个文件名是「1.定义多个Tool.py」，以数字开头、还带中文和点，
#   Python 的 import 语句吃不下这种名字。
#   学习阶段最简单的办法：直接复制粘贴过来。
#   （真实项目里工具会单独放一个 tools.py，就为的是能被 import）
