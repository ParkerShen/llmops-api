# ============================================================
# 第 2 步：定义一个参数是 int 的 Tool
# 要求：
#   1. 参数标注 int（不是 str）
#   2. 中文 docstring 说明用途
#   3. 返回一句话，把参数拼进去
# 这次我不给占位函数了，整个函数你自己写。
# 照着 1.字符串参数Tool.py 的结构来，只把 str 换成 int。
# TODO(你写)：
# ------------------------------------------------------------
@tool
def get_weather_info(price: int,city:str) -> str:
    """查询指定城市未来某天的航班价格

Args:
    city: 出发城市的中文名，例如「深圳」
    price: 机票价格，单位元
"""
    return f"香港到{city}的机票价格是{price}元"

