from langchain_core.tools import tool

# ============================================================
# 第 2 步：定义一个有两个参数的 Tool
# 要求：
#   1. 两个参数，类型故意不一样：一个 str，一个 int
#      自己挑业务，比如 get_flight_price(city: str, days: int)
#   2. docstring 里要把「两个参数各自是什么」说清楚，
#      不要只写一句「查询航班价格」就完事
#   3. 返回一句话，把两个参数都拼进去
# TODO(你写)：
# ------------------------------------------------------------
@tool
def get_weather_info(price: int,city:str) -> str:
    """查询指定城市未来某天的航班价格

Args:
    city: 出发城市的中文名，例如「深圳」
    price: 机票价格，单位元
"""
    return f"香港到{city}的机票价格是{price}元"

# ============================================================
# 第 3 步：打印 xxx.args
# 看清楚两件事：
#   A. 外层字典有几个 key？
#   B. 每个 key 对应的 type 分别是什么？
# TODO(你写)：
# ------------------------------------------------------------
print(get_weather_info.args)

# ============================================================
# 第 4 步：实验 —— 顺序到底重不重要
# 调换 invoke 字典里两个 key 的先后顺序，反着写一遍，跑两次。
#
# 问题：两次输出一样吗？为什么？
# 提示：想想上一章 .invoke() 源码里那句 tool_input.copy()
#       传下去之后，函数是怎么知道哪个值该给哪个参数的？
# TODO(你写)：
# ------------------------------------------------------------

print(get_weather_info.invoke({"city": "北京","price":'1000'}))
