from langchain_core.tools import tool
import json  # ← 标准库

# ============================================================
# 第 2 步：定义一个「有一个可选参数」的 Tool
# 要求：
#   1. 两个参数：第一个必填，第二个给一个「Python 默认值」
#      写法就是普通 Python：def f(a: str, b: int = 1)
#   2. docstring 里说明第二个参数不传时代表什么
#   3. 函数体 return 一句话，把两个参数都拼进去
# TODO(你写)：
# ------------------------------------------------------------
@tool
def get_weather(city: str, heat: int = 30)-> str:
    """根据城市查询天气，heat 是体感温度，如果不传则是30°"""
    return f"{city}今天的温度是{heat}°"


# ============================================================
# 第 3 步：对比两种 schema —— 这一步是本章重点
#
# 打印两个东西，并排看：
#   ① xxx.args                        ← 你前面几章一直在用的
#   ② xxx.args_schema.model_json_schema()   ← 完整版
#
# 提示：用 print(json.dumps(..., ensure_ascii=False, indent=2)) 才看得清
#
# 要回答的问题：
#   A. 有默认值的那个参数，schema 里多了什么字段？
#   B. 完整版里多出了一个叫 required 的东西 ——
#      .args 里有它吗？它里面列了几个参数？
#   C. 猜一下：真正发给 LLM 的是简化版还是完整版？
# TODO(你写)：
# ------------------------------------------------------------
print(get_weather.args)
print(json.dumps(get_weather.args_schema.model_json_schema(), ensure_ascii=False, indent=2))

# ============================================================
# 第 4 步：实验 —— 不传那个可选参数会怎样
#
# invoke 的时候，字典里只写必填的那个，第二个故意不写。
#
# 要回答的问题：
